def _e(value):
    return html.escape(str(value), quote=True)


def _lang(locale):
    return "pt" if locale.startswith("pt") else "en"


def _baseline_shots(root: Path, state, out: Path):
    shots = []
    for art_id, art in sorted(state["artifacts"].items()):
        if art["kind"] != "experience-baseline":
            continue
        try:
            doc, issues = contracts.parse(workspace.resolve(root, art["path"]).read_text(encoding="utf-8"))
        except (OSError, LfeError):
            continue
        if issues or contracts.validate(doc, expected="baseline"):
            continue
        for screen in doc["screens"]:
            preview = screen.get("preview", {}).get("path")
            if not preview or contracts.unsafe_path(preview) or not (root / preview).is_file():
                continue
            rel = os.path.relpath(root / preview, out.parent).replace(os.sep, "/")
            shots.append({"src": rel, "caption": f"{art_id} r{art['revision']} · {screen['screenId']} · {screen['name']}",
                          "fidelity": doc["fidelity"]})
    return shots


def _trace(root: Path):
    try:
        from . import evidence
        return evidence.trace(root)["requirements"]
    except (ImportError, LfeError, KeyError):
        return []


def build_html(root: Path, out: Path):
    doc = handoff.build(root)
    state = workspace.load_state(root)
    lang = _lang(doc["locale"])
    t, labels, glabel = UI[lang], STAGE_LABEL[lang], GATE_LABEL[lang]
    current = STAGES.index(doc["stage"])
    unlocked = doc["productionCode"] == "unlocked"

    aria_now = ' aria-current="step"'
    stages = "".join(
        f'<li class="{"now" if i == current else "done" if i < current else ""}"'
        f'{aria_now if i == current else ""}><span class="num">S{i}</span>{_e(labels[i])}</li>'
        for i in range(10))

    computed = gates.evaluate(root, state, ledger.read(root))
    gate_cards = []
    for g in doc["gates"]:
        tone = STATUS_TONE.get(g["status"], "idle")
        source = {"simulated-human": t["simulated"], "chat-quote": t["chat"]}.get(g["channel"],
                                                                                  t["human"] if g["channel"] else "")
        bound = ", ".join(g["boundTo"])
        reasons = "".join(f"<li>{_e(r)}</li>" for r in g["reasons"])
        pending = "".join(
            f'<li class="exc">{_e(t["exception"])} {_e(x["id"])}: {_e(x["description"])} — {_e(t["blocks"])} {_e(x["mustResolveBefore"])}</li>'
            for x in computed[g["gate"]]["exceptions"])
        gate_cards.append(
            f'<article class="gate {tone}" aria-label="{_e(g["gate"])} {_e(g["status"])}">'
            f'<div class="top"><span class="id">{_e(g["gate"])}</span><span class="pill {tone}">{_e(g["status"])}</span></div>'
            f'<h3>{_e(glabel[g["gate"]])}</h3>'
            f'<div class="small">{_e(g["decisionId"] or "—")}{" · " + _e(source) if source else ""}</div>'
            f'{f"<div class=small>{_e(bound)}</div>" if bound else ""}'
            f'{f"<ul>{reasons}{pending}</ul>" if reasons or pending else ""}</article>')

    shots = _baseline_shots(root, state, out)
    shots_html = "".join(
        f'<figure><img src="{_e(s["src"])}" alt="{_e(s["caption"])}" loading="lazy">'
        f'<figcaption>{_e(s["caption"])} · <code>{_e(s["fidelity"])}</code></figcaption></figure>' for s in shots
    ) or f'<p class="small">{_e(t["none"])}</p>'

    trace_rows = "".join(
        f'<tr><td><code>{_e(r["id"])}</code></td><td>{_e(r["status"])}</td><td>{_e(", ".join(r["tests"]) or "—")}</td>'
        f'<td class="{"yes" if r["passing"] else "no" if not r["ok"] else ""}">'
        f'{_e(", ".join(r["passing"]) or r.get("missing", "—"))}</td></tr>' for r in _trace(root))
    trace_html = (f'<table><thead><tr><th>{_e(t["req"])}</th><th>status</th><th>{_e(t["tests"])}</th>'
                  f'<th>{_e(t["proof"])}</th></tr></thead><tbody>{trace_rows}</tbody></table>'
                  if trace_rows else f'<p class="small">{_e(t["none"])}</p>')

    receipts = "".join(
        f'<tr><td><code>{_e(r["id"])}</code></td><td><code>{_e(r["testId"])}</code></td>'
        f'<td class="{"yes" if r["status"] == "pass" else "no"}">{_e(r["status"])}</td></tr>' for r in doc["lastReceipts"])
    receipts_html = (f"<table><tbody>{receipts}</tbody></table>" if receipts else f'<p class="small">{_e(t["none"])}</p>')

    questions = "".join(f"<li><code>{_e(q['id'])}</code> {_e(q['question'])} <span class='small'>({_e(q['class'])})</span></li>"
                        for q in doc["openQuestions"]) or f"<li>{_e(t['none'])}</li>"
    rules = "".join(f"<li>{_e(r)}</li>" for r in doc["prohibitions"])

    return f"""<!doctype html>
<html lang="{"pt-BR" if lang == "pt" else "en"}"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; img-src 'self'; style-src 'unsafe-inline'">
<title>LFE Studio — {_e(doc["name"])}</title><style>{CSS}</style></head>
<body>
<header>
  <div><h1>{_e(doc["name"])}</h1><div class="meta"><code>{_e(doc["projectId"])}</code> · {_e(t["stage"])} {_e(doc["stage"])} — {_e(labels[current])}</div></div>
  <span class="badge {"ok" if unlocked else "bad"}" role="status">{"🔓" if unlocked else "🔒"} {_e(t["unlocked"] if unlocked else t["locked"])}</span>
</header>
<main>
  <nav aria-label="{_e(t["stages"])}"><section><h2>{_e(t["stages"])}</h2><ol class="stages">{stages}</ol></section></nav>
  <div>
    <section aria-labelledby="g"><h2 id="g">{_e(t["gates"])}</h2><div class="gates">{"".join(gate_cards)}</div>
      <p class="small">{_e(t["legend"])}</p></section>
    <section aria-labelledby="d"><h2 id="d">{_e(t["design"])}</h2><div class="shots">{shots_html}</div></section>
  </div>
  <aside>
    <section aria-labelledby="t"><h2 id="t">{_e(t["trace"])}</h2>{trace_html}</section>
    <section aria-labelledby="r"><h2 id="r">{_e(t["receipts"])}</h2>{receipts_html}</section>
  </aside>
</main>
<footer>
  <div class="next"><strong>{_e(t["next"])}:</strong> {_e(doc["nextAction"])}
    <h2 style="margin-top:14px">{_e(t["questions"])}</h2><ul class="plain">{questions}</ul>
    <h2 style="margin-top:14px">{_e(t["rules"])}</h2><ul class="plain">{rules}</ul></div>
  <p class="small">{_e(t["generated"])} · ledger <code>{_e(doc["ledgerHead"][:19])}…</code> · {_e(doc["generatedAt"])}</p>
</footer>
</body></html>
"""


def write(root: Path, out: Path | None = None):
    root = Path(root)
    out = Path(out) if out else root / ".lfe" / "studio.html"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(build_html(root, out), encoding="utf-8")
    return out
