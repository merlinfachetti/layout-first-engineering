"""Continuity: handoff, notes, export/import and session hooks (RFC-0001 8.7, I-08, I-10; RFC-0002 AC-10).

The handoff is always generated from the ledger, the state and the evidence on disk, never written
by hand, so a new session (or another tool) resumes from facts instead of a conversation's memory.
"""
from __future__ import annotations

import base64
import json
from pathlib import Path

from . import contracts, gates, ledger, schema_lite, workspace
from .workspace import GATES, LfeError

BUNDLE_VERSION = "lfe.bundle/0.1"
EVIDENCE_DIR = Path(".lfe") / "evidence"
HANDOFF_MD = Path(".lfe") / "HANDOFF.md"


def _receipts(root: Path):
    found = []
    for path in sorted((root / EVIDENCE_DIR).glob("EVID-*.json")):
        doc, issues = contracts.parse(path.read_text(encoding="utf-8"))
        if not issues and isinstance(doc, dict):
            found.append({"id": doc.get("id"), "testId": doc.get("testId"), "status": doc.get("status"),
                          "startedAt": doc.get("startedAt")})
    return found[-10:]


def _prohibitions(results):
    rules = ["Never record G2–G6 approvals: ask the person to run `lfe approve <gate>` in their own terminal.",
             "Never deploy, publish, delete data or spend money without a specific, separate authorization."]
    if not all(gates.is_valid(results, g) for g in ("G2", "G3", "G4")):
        rules.insert(0, "Do not write production code: G2, G3 and G4 are not all valid.")
    for gate in GATES:
        if results[gate]["status"] == "stale":
            rules.append(f"{gate} is stale: show what changed and ask for a new decision before relying on it.")
    return rules


def build(root: Path):
    state = workspace.load_state(root)
    entries = ledger.read(root)
    results = gates.evaluate(root, state, entries)
    effective = {e["gate"]: e for e in entries if e["kind"] == "decision"}
    doc = {
        "schemaVersion": "lfe.handoff/0.1",
        "projectId": state["projectId"],
        "name": state["name"],
        "locale": state["locale"],
        "stage": state["stage"],
        "gates": [{
            "gate": g,
            "status": results[g]["status"],
            "decisionId": results[g]["decisionId"],
            "channel": effective[g]["channel"] if g in effective else None,
            "boundTo": [f"{a['id']}@r{a['revision']}" for a in effective[g]["scope"]["artifacts"]] if g in effective else [],
            "reasons": results[g]["reasons"],
        } for g in GATES],
        "productionCode": "unlocked" if all(gates.is_valid(results, g) for g in ("G2", "G3", "G4")) else "locked",
        "openQuestions": state.get("openQuestions", []),
        "lastReceipts": _receipts(root),
        "nextAction": state["nextAction"],
        "prohibitions": _prohibitions(results),
        "ledgerHead": entries[-1]["hash"] if entries else ledger.GENESIS,
        "generatedAt": workspace.now(),
    }
    problems = schema_lite.validate(doc, contracts.load_schema("handoff"))
    if problems:
        raise LfeError("SCHEMA_VIOLATION", f"generated handoff invalid: {problems[0]}", 1)
    return doc


TEXT = {
    "pt-BR": {"title": "Handoff do projeto", "stage": "Estágio", "prod": "Código de produção", "next": "Próxima ação",
              "gates": "Gates", "questions": "Perguntas abertas", "receipts": "Últimos recibos de teste",
              "rules": "Não faça", "none": "nenhuma", "generated": "Gerado por `lfe handoff` — não editar à mão."},
    "en": {"title": "Project handoff", "stage": "Stage", "prod": "Production code", "next": "Next action",
           "gates": "Gates", "questions": "Open questions", "receipts": "Latest test receipts",
           "rules": "Do not", "none": "none", "generated": "Generated by `lfe handoff` — do not edit by hand."},
}


def render_markdown(doc):
    t = TEXT["pt-BR" if doc["locale"].startswith("pt") else "en"]
    lines = [f"# {t['title']} — {doc['name']}", "", f"> {t['generated']}", "",
             f"- **{t['stage']}:** {doc['stage']}",
             f"- **{t['prod']}:** {doc['productionCode']}",
             f"- **{t['next']}:** {doc['nextAction']}", "",
             f"## {t['gates']}", "", "| Gate | Status | Decision | Bound to | Notes |", "| --- | --- | --- | --- | --- |"]
    for g in doc["gates"]:
        notes = "; ".join(g["reasons"]).replace("|", "/") or "—"
        lines.append(f"| {g['gate']} | {g['status']} | {g['decisionId'] or '—'} | {', '.join(g['boundTo']) or '—'} | {notes} |")
    lines += ["", f"## {t['questions']}", ""]
    lines += [f"- {q['id']} ({q['class']}, {q['stage']}): {q['question']}" for q in doc["openQuestions"]] or [f"- {t['none']}"]
    lines += ["", f"## {t['receipts']}", ""]
    lines += [f"- {r['id']} · {r['testId']} · {r['status']}" for r in doc["lastReceipts"]] or [f"- {t['none']}"]
    lines += ["", f"## {t['rules']}", ""] + [f"- {rule}" for rule in doc["prohibitions"]]
    return "\n".join(lines) + "\n"


def write(root: Path):
    doc = build(root)
    (root / HANDOFF_MD).write_text(render_markdown(doc), encoding="utf-8")
    return doc


def brief(doc):
    """A compact context block for a new agent session (SessionStart hook)."""
    gate_line = " ".join(f"{g['gate']}={g['status']}" for g in doc["gates"])
    blockers = [q for q in doc["openQuestions"] if q["class"] == "blocker"]
    parts = [f"LFE project '{doc['name']}' ({doc['projectId']}) resumed from .lfe/ — do not restart discovery.",
             f"Stage {doc['stage']}; {gate_line}; production code {doc['productionCode']}.",
             f"Next action: {doc['nextAction']}"]
    if blockers:
        parts.append("Blocking questions: " + "; ".join(f"{q['id']} {q['question']}" for q in blockers))
    parts.append("Rules: " + " ".join(doc["prohibitions"]))
    parts.append("Run `lfe status` for details; full handoff in .lfe/HANDOFF.md.")
    return "\n".join(parts)


# --- notes that make a resume meaningful -----------------------------------------------------

def set_next(root: Path, text):
    if not text.strip():
        raise LfeError("EMPTY_NEXT_ACTION", "the next action cannot be empty", 2)
    state = workspace.load_state(root)
    state["nextAction"] = text.strip()
    workspace.save_state(root, state)
    return write(root)


def add_question(root: Path, text, klass, stage=None):
    state = workspace.load_state(root)
    questions = state.setdefault("openQuestions", [])
    taken = [int(q["id"][2:]) for q in questions]
    question = {"id": f"Q-{(max(taken) + 1 if taken else 1):03d}", "stage": stage or state["stage"],
                "question": text.strip(), "class": klass}
    questions.append(question)
    workspace.save_state(root, state)
    write(root)
    return question


def close_question(root: Path, qid):
    state = workspace.load_state(root)
    before = len(state.get("openQuestions", []))
    state["openQuestions"] = [q for q in state.get("openQuestions", []) if q["id"] != qid]
    if len(state["openQuestions"]) == before:
        raise LfeError("UNKNOWN_REFERENCE", f"{qid} is not an open question", 6)
    workspace.save_state(root, state)
    return write(root)


# --- export / import (AC-10, I-08) -----------------------------------------------------------

def _bundle_files(root: Path, state):
    paths = set()
    for art in state["artifacts"].values():
        paths.add(art["path"])
        doc, issues = contracts.parse((workspace.resolve(root, art["path"])).read_text(encoding="utf-8", errors="replace"))
        if not issues and isinstance(doc, dict):
            paths.update(f["path"] for f in doc.get("files", []) if isinstance(f, dict) and "path" in f)
    for receipt in (root / EVIDENCE_DIR).glob("EVID-*.json"):
        paths.add(receipt.relative_to(root).as_posix())
        doc, issues = contracts.parse(receipt.read_text(encoding="utf-8"))
        if not issues and isinstance(doc, dict):
            paths.update(a["path"] for a in doc.get("artifacts", []) if isinstance(a, dict) and "path" in a)
    files = []
    for rel in sorted(paths):
        target = workspace.resolve(root, rel)
        if target.is_file():
            data = target.read_bytes()
            files.append({"path": rel, "sha256": contracts.sha256_of(data), "base64": base64.b64encode(data).decode("ascii")})
    return files


def export(root: Path):
    state = workspace.load_state(root)
    entries = ledger.read(root)  # refuses to export a tampered ledger
    return {"schemaVersion": BUNDLE_VERSION, "exportedAt": workspace.now(), "state": state,
            "decisions": entries, "files": _bundle_files(root, state)}


def import_bundle(root: Path, bundle):
    if not isinstance(bundle, dict) or bundle.get("schemaVersion") != BUNDLE_VERSION:
        raise LfeError("INCOMPATIBLE_SCHEMA", f"expected {BUNDLE_VERSION}, got {bundle.get('schemaVersion') if isinstance(bundle, dict) else type(bundle).__name__}", 4)
    if (root / workspace.STATE_FILE).exists():
        raise LfeError("ALREADY_INITIALIZED", f"{root / workspace.STATE_FILE} exists; import into an empty folder", 2)
    issues = contracts.validate(bundle["state"], expected="state")
    if issues:
        raise LfeError(issues[0].code, f"bundle state: {issues[0]}", 6)
    prev = ledger.GENESIS
    for number, entry in enumerate(bundle["decisions"], start=1):
        problems = contracts.validate(entry, expected="decision")
        if problems or entry["seq"] != number or entry["prevHash"] != prev or ledger.entry_hash(entry) != entry["hash"]:
            raise LfeError("LEDGER_TAMPERED", f"bundle decision {number} fails verification", 5)
        prev = entry["hash"]
    for item in bundle["files"]:
        data = base64.b64decode(item["base64"], validate=True)
        if contracts.sha256_of(data) != item["sha256"]:
            raise LfeError("EVIDENCE_TAMPERED", f"bundle file {item['path']} does not match its hash", 5)
        workspace.resolve(root, item["path"])  # refuses unsafe paths before anything is written
    for item in bundle["files"]:
        target = workspace.resolve(root, item["path"])
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(base64.b64decode(item["base64"]))
    workspace.write_json_atomic(root / workspace.STATE_FILE, bundle["state"])
    (root / workspace.LEDGER_FILE).write_text(
        "".join(contracts.canonical_json(e).decode("utf-8") + "\n" for e in bundle["decisions"]), encoding="utf-8")
    ledger.read(root)
    return write(root)


def to_json(doc):
    return json.dumps(doc, indent=2, ensure_ascii=False)
